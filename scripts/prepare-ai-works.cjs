const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'wrangler.jsonc'), 'utf8'));
const expectedOrigin = 'https://github.com/kyotomalmal25-sudo/ai-web-gallery';
const origin = execFileSync('git', ['remote', 'get-url', 'origin'], { cwd: root, encoding: 'utf8' }).trim().replace(/\.git$/, '').replace(/\/$/, '');
function requireCheck(ok, message) { if (!ok) throw new Error(`AI Works deployment refused: ${message}`); }
requireCheck(origin === expectedOrigin, 'wrong source repository');
requireCheck(config.name === 'banana-needs-no-reason', 'wrong Worker name');
requireCheck(config.account_id === '88dc9da24144ad2c2056a9ef34e4ce56', 'wrong Cloudflare account');
requireCheck(config.main === 'work-worker.js', 'wrong Worker entrypoint');
requireCheck(config.assets.directory === 'dist/ai-works' && config.assets.binding === 'ASSETS', 'wrong asset directory/binding');
requireCheck(JSON.stringify(config.assets.run_worker_first) === JSON.stringify(['/', '/work/*']), 'dynamic routes must run the Worker first');
requireCheck(config.keep_vars === true && config.workers_dev === true, 'production settings must be preserved');
requireCheck(!config.env && !config.routes, 'unexpected environment or route overrides');
requireCheck(!process.env.CLOUDFLARE_ENV, 'CLOUDFLARE_ENV must be unset');
requireCheck(!process.env.CLOUDFLARE_ACCOUNT_ID || process.env.CLOUDFLARE_ACCOUNT_ID === config.account_id, 'account environment override does not match AI Works');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const worker = fs.readFileSync(path.join(root, config.main), 'utf8');
requireCheck(/<title>AI Works(?:\s*\/[^<]*)?<\/title>/.test(html), 'index.html is not the AI Works site');
requireCheck(worker.includes("table: 'works'") && worker.includes("const BUCKET = 'ai-works'") && worker.includes('renderWorkPage'), 'Supabase work routes are missing');
const output = path.join(root, config.assets.directory);
requireCheck(output === path.join(root, 'dist', 'ai-works'), 'unsafe staging path');
fs.rmSync(output, { recursive: true, force: true });
fs.mkdirSync(output, { recursive: true });
const files = ['index.html', 'styles.css', 'app.js', 'supabase-client.js', 'supabase-config.js', 'robots.txt', 'sitemap.xml'];
for (const file of files) fs.copyFileSync(path.join(root, file), path.join(output, file));
for (const dir of ['assets', 'works', 'work']) fs.cpSync(path.join(root, dir), path.join(output, dir), { recursive: true });
console.log('AI Works source and target verified; public files staged in dist/ai-works.');
